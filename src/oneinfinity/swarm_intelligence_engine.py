def create_agent(
    agent_type:     AgentType,
    tool_registry:  Optional[Any] = None,
    attack_graph:   Optional[Any] = None,
    knowledge_base: Optional[Any] = None,
    shared_state:   Optional[Dict] = None,
) -> SwarmAgent:
    """Factory: instantiate the correct SwarmAgent subclass by AgentType."""
    cls = _AGENT_CLASSES.get(agent_type, SwarmAgent)
    return cls(
        tool_registry  = tool_registry,
        attack_graph   = attack_graph,
        knowledge_base = knowledge_base,
        shared_state   = shared_state,
    )


def create_full_swarm(
    tool_registry:  Optional[Any] = None,
    attack_graph:   Optional[Any] = None,
    knowledge_base: Optional[Any] = None,
    shared_state:   Optional[Dict] = None,
    agent_types:    Optional[List[AgentType]] = None,
) -> Dict[AgentType, SwarmAgent]:
    """
    Create one agent of every requested type (default: all 8).
    Returns a dict mapping AgentType → SwarmAgent instance.
    """
    types = agent_types or list(AgentType)
    return {
        at: create_agent(at, tool_registry, attack_graph, knowledge_base, shared_state)
        for at in types
    }


