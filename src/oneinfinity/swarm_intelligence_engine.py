# ── Data models ───────────────────────────────────────────────────────────────

@dataclass
class Hypothesis:
    """A single attack hypothesis generated by an agent."""
    hypothesis_id:  str
    agent_type:     AgentType
    target_node:    str           # URL / node-id
    attack_vector:  str           # e.g. "reflected_xss:q"
    confidence:     float         # 0.0 – 1.0 prior estimate
    payload:        str
    context:        Dict[str, Any] = field(default_factory=dict)
    reasoning:      str = ""
    priority:       float = 0.5   # 0 = low, 1 = high


@dataclass
class AgentFinding:
    """A confirmed (or high-confidence suspected) vulnerability."""
    finding_id:     str
    agent_id:       str
    agent_type:     AgentType
    target:         str
    vuln_type:      str
    severity:       str            # critical / high / medium / low / info
    title:          str
    description:    str
    payload:        str
    evidence:       str
    cvss:           float
    confidence:     float
    reproduced:     bool
    graph_node_id:  Optional[str]  = None
    chain_potential: List[str]     = field(default_factory=list)
    remediation:    str            = ""
    timestamp:      float          = field(default_factory=time.time)

    def to_kb_dict(self) -> Dict:
        """Convert to format expected by KnowledgeBase.record_finding()."""
        return {
            "target":      self.target,
            "vuln_type":   self.vuln_type,
            "severity":    self.severity,
            "cvss_score":  self.cvss,
            "endpoint":    self.target,
            "parameter":   self.payload[:120] if self.payload else "",
            "source_tool": self.agent_id,
            "chain_id":    ",".join(self.chain_potential),
        }


@dataclass
class AgentMemory:
    """
    Per-agent persistent memory for cross-session learning.
    Success rates are updated via Exponential Moving Average (EMA).
    """
    successful_payloads:  List[Dict] = field(default_factory=list)
    failed_payloads:      List[Dict] = field(default_factory=list)
    pattern_rates:        Dict[str, float] = field(default_factory=dict)  # vector → rate
    tech_best_payloads:   Dict[str, List[str]] = field(default_factory=dict)
    total_tests:          int = 0
    successful_tests:     int = 0

    EMA_ALPHA = 0.30  # weight for new observations

    @property
    def success_rate(self) -> float:
        if self.total_tests == 0:
            return 0.40  # neutral prior
        return self.successful_tests / self.total_tests

    def update_rate(self, vector: str, success: bool) -> None:
        prev = self.pattern_rates.get(vector, 0.40)
        obs  = 1.0 if success else 0.0
        self.pattern_rates[vector] = (1 - self.EMA_ALPHA) * prev + self.EMA_ALPHA * obs
        self._normalize_rates()

    def apply_decay(self, decay_factor: float = 0.9) -> None:
        """Gradually decay learned rates over time to prevent stagnation."""
        for vector in self.pattern_rates:
            # Decay towards the neutral prior of 0.40
            current = self.pattern_rates[vector]
            self.pattern_rates[vector] = 0.40 + (current - 0.40) * decay_factor

    def _normalize_rates(self) -> None:
        """Prevent overfitting by limiting max variance."""
        rates = list(self.pattern_rates.values())
        if not rates:
            return
        avg = sum(rates) / len(rates)
        for vector, rate in self.pattern_rates.items():
            if rate > 0.95:
                self.pattern_rates[vector] = 0.95  # Cap absolute certainty
            elif rate < 0.05:
                self.pattern_rates[vector] = 0.05  # Floor absolute failure

    def rate(self, vector: str, default: float = 0.40) -> float:
        return self.pattern_rates.get(vector, default)

    def top_payloads(self, n: int = 8) -> List[str]:
        """Return payloads ranked by associated vector success rate."""
        scored = [
            (self.pattern_rates.get(p.get("vector", ""), 0) * p.get("confidence", 0.5), p["payload"])
            for p in self.successful_payloads[-60:]
        ]
        scored.sort(reverse=True)
        return [pay for _, pay in scored[:n]]


# ── Base agent ────────────────────────────────────────────────────────────────

class SwarmAgent(ABC):
    """
    Abstract base for all swarm intelligence agents.

    Subclasses implement:
      - generate_hypotheses()  — domain-specific hypothesis generation
      - execute_tests()        — domain-specific tool execution
    """

    # Subclasses declare which NodeTypes they care about
    RELEVANT_NODE_TYPES: List[str] = []
    RELEVANT_LABEL_KEYWORDS: List[str] = []

    def __init__(
        self,
        agent_type:     AgentType,
        tool_registry:  Optional[Any] = None,
        attack_graph:   Optional[Any] = None,
        knowledge_base: Optional[Any] = None,
        shared_state:   Optional[Dict] = None,
    ):
        self.agent_id       = f"{agent_type.value}_{uuid.uuid4().hex[:8]}"
        self.agent_type     = agent_type
        self.tool_registry  = tool_registry
        self.attack_graph   = attack_graph
        self.knowledge_base = knowledge_base
        self.shared_state   = shared_state if shared_state is not None else {}
        self.status         = AgentStatus.IDLE
        self.memory         = AgentMemory()
        self.findings:  List[AgentFinding] = []
        self.hypotheses: List[Hypothesis]  = []
        self._stop_event = asyncio.Event()
        # ── Priority 6: Memory persistence path ──────────────────────────
        try:
            from oneinfinity.path_manager import db_path as _dp
            _mem_dir = Path(str(_dp("."))).parent / "agent_memories"
        except Exception:
            _mem_dir = Path.home() / ".oneinfinity" / "agent_memories"
        self._memory_path = _mem_dir / f"agent_{agent_type.value}.json"
        self._load_memory()
        logger.debug("[%s] Initialized", self.name)

    @property
    def name(self) -> str:
        return f"{self.agent_type.value.upper()}-{self.agent_id[-4:].upper()}"

    def stop(self) -> None:
        self._stop_event.set()

    # ── Main lifecycle ────────────────────────────────────────────────────────

    async def run(self, target: str, context: Dict[str, Any]) -> List[AgentFinding]:
        """
        Full agent lifecycle:
          analyze → hypothesize → test → report → learn
        Returns all findings discovered during this run.
        """
        start_time = time.time()
        try:
            self.status = AgentStatus.ANALYZING
            graph_nodes = await self.analyze_graph(target, context)

            self.status = AgentStatus.HYPOTHESIZING
            hypotheses = await self.generate_hypotheses(target, graph_nodes, context)
            self.hypotheses = hypotheses
            logger.info("[%s] %d hypotheses for %s", self.name, len(hypotheses), target)

            self.status = AgentStatus.TESTING
            findings = await self.execute_tests(target, hypotheses, context)
            self.findings.extend(findings)

            self.status = AgentStatus.REPORTING
            await self.report_findings(findings)

            self.status = AgentStatus.LEARNING
            await self.learn_from_results(findings, hypotheses)

            self.status = AgentStatus.DONE
            elapsed = time.time() - start_time
            logger.info("[%s] Done in %.1fs — %d findings", self.name, elapsed, len(findings))
            return findings

        except asyncio.CancelledError:
            self.status = AgentStatus.IDLE
            return self.findings
        except Exception as exc:
            self.status = AgentStatus.FAILED
            logger.error("[%s] Unhandled error: %s", self.name, exc)
            return self.findings

    # ── Graph analysis ────────────────────────────────────────────────────────

    async def analyze_graph(self, target: str, context: Dict) -> List[Dict]:
        """Collect relevant graph nodes + context endpoints into a unified list."""
        nodes: List[Dict] = []

        if self.attack_graph and _GRAPH_AVAILABLE:
            try:
                for ntype in self.RELEVANT_NODE_TYPES:
                    matches = self.attack_graph.find_nodes(node_type=ntype)
                    for n in matches:
                        nodes.append({"id": n.id, "label": n.label,
                                      "type": n.node_type, "props": n.properties})
                for keyword in self.RELEVANT_LABEL_KEYWORDS:
                    matches = self.attack_graph.find_nodes(label_contains=keyword)
                    for n in matches:
                        entry = {"id": n.id, "label": n.label,
                                 "type": n.node_type, "props": n.properties}
                        if entry not in nodes:
                            nodes.append(entry)
            except Exception as exc:
                logger.debug("[%s] Graph analysis: %s", self.name, exc)

        # Supplement with raw endpoint list from context
        for ep in context.get("endpoints", []):
            nodes.append({"id": ep, "label": ep, "type": "url", "props": {}})

        return nodes

    # ── Abstract methods ──────────────────────────────────────────────────────

    @abstractmethod
    async def generate_hypotheses(
        self, target: str, graph_nodes: List[Dict], context: Dict
    ) -> List[Hypothesis]:
        """Generate prioritised attack hypotheses from graph nodes + context."""

    @abstractmethod
    async def execute_tests(
        self, target: str, hypotheses: List[Hypothesis], context: Dict
    ) -> List[AgentFinding]:
        """Execute tests against hypotheses, return confirmed findings."""

    # ── Reporting ─────────────────────────────────────────────────────────────

    async def report_findings(self, findings: List[AgentFinding]) -> None:
        """
        1. Append to shared_state["findings"]
        2. Add vulnerability nodes to the attack graph
        3. Emit to shared_state event bus if present
        """
        if not findings:
            return

        # Shared state
        self.shared_state.setdefault("findings", []).extend(findings)

        # Attack graph
        if self.attack_graph and _GRAPH_AVAILABLE:
            for f in findings:
                try:
                    node = self.attack_graph.add_node(
                        node_type  = NodeType.VULNERABILITY,
                        label      = f.title,
                        properties = {
                            "vuln_type":  f.vuln_type,
                            "payload":    f.payload[:500],
                            "confidence": f.confidence,
                            "agent":      self.agent_id,
                            "evidence":   f.evidence[:500],
                            "chains":     f.chain_potential,
                        },
                        severity    = f.severity,
                        risk_score  = f.cvss,
                        exploitable = f.reproduced,
                        source      = self.agent_id,
                    )
                    f.graph_node_id = node.id
                    # Edge: endpoint → vulnerability
                    if f.target:
                        ep_nodes = self.attack_graph.find_nodes(label_contains=f.target)
                        if ep_nodes:
                            self.attack_graph.add_edge(
                                ep_nodes[0].id, node.id,
                                edge_type=EdgeType.HAS_VULNERABILITY,
                                label=f.vuln_type,
                                probability=f.confidence,
                                source_engine=self.agent_id,
                            )
                except Exception as exc:
                    logger.debug("[%s] Graph update error: %s", self.name, exc)

        # Event bus (coordinator injects a queue)
        event_queue: Optional[asyncio.Queue] = self.shared_state.get("event_queue")
        if event_queue:
            for f in findings:
                await event_queue.put({"type": "finding", "agent": self.agent_id,
                                       "agent_type": self.agent_type, "finding": f})

        logger.info("[%s] Reported %d findings", self.name, len(findings))

    # ── Learning ──────────────────────────────────────────────────────────────

    async def learn_from_results(
        self, findings: List[AgentFinding], hypotheses: List[Hypothesis]
    ) -> None:
        """Update EMA rates and persist to KB."""
        # Apply time decay to historical learning before adding new observations
        self.memory.apply_decay(decay_factor=0.95)

        confirmed_payloads = {f.payload for f in findings if f.confidence >= 0.70}

        for h in hypotheses:
            self.memory.total_tests += 1
            success = h.payload in confirmed_payloads
            if success:
                self.memory.successful_tests += 1
                self.memory.successful_payloads.append({
                    "payload":    h.payload,
                    "vector":     h.attack_vector,
                    "confidence": h.confidence,
                })
            else:
                self.memory.failed_payloads.append({
                    "payload": h.payload,
                    "vector":  h.attack_vector,
                })
            self.memory.update_rate(h.attack_vector, success)

        # Persist to KB
        if self.knowledge_base and findings and _KB_AVAILABLE:
            session_id = self.shared_state.get("session_id", self.agent_id)
            for f in findings:
                try:
                    self.knowledge_base.record_finding_sync(
                        session_id=session_id,
                        finding=f.to_kb_dict(),
                        confirmed=f.reproduced,
                    )
                    self.knowledge_base.record_tool_run_sync(
                        tool_name=self.agent_type.value,
                        vuln_type=f.vuln_type,
                        target_type="web",
                        success=True,
                        findings_count=1,
                        duration_s=0.0,
                    )
                except Exception:
                    pass

        # ── Priority 6: Persist memory to disk for cross-scan learning ────
        self._save_memory()

    # ── Memory Persistence ────────────────────────────────────────────────────

    def _load_memory(self) -> None:
        """Reload persisted AgentMemory from disk (cross-scan learning)."""
        try:
            if self._memory_path.exists():
                data = json.loads(self._memory_path.read_text())
                self.memory.pattern_rates = data.get("pattern_rates", {})
                self.memory.total_tests = data.get("total_tests", 0)
                self.memory.successful_tests = data.get("successful_tests", 0)
                # Restore successful payloads (cap at 100 to bound memory)
                self.memory.successful_payloads = data.get("successful_payloads", [])[-100:]
                logger.info(
                    "[%s] Memory loaded: %d vectors, %d/%d tests",
                    self.agent_type.value,
                    len(self.memory.pattern_rates),
                    self.memory.successful_tests,
                    self.memory.total_tests,
                )
        except Exception as exc:
            logger.debug("[%s] Memory load skipped (starting fresh): %s", self.agent_type.value, exc)

    def _save_memory(self) -> None:
        """Persist AgentMemory to disk so the next scan benefits from current learnings."""
        try:
            self._memory_path.parent.mkdir(parents=True, exist_ok=True)
            data = {
                "agent_type": self.agent_type.value,
                "pattern_rates": self.memory.pattern_rates,
                "total_tests": self.memory.total_tests,
                "successful_tests": self.memory.successful_tests,
                "successful_payloads": self.memory.successful_payloads[-100:],
                "saved_at": time.time(),
            }
            self._memory_path.write_text(json.dumps(data, indent=2))
            logger.debug("[%s] Memory saved (%d vectors)", self.agent_type.value,
                         len(self.memory.pattern_rates))
        except Exception as exc:
            logger.debug("[%s] Memory save failed: %s", self.agent_type.value, exc)

    # ── Helpers ───────────────────────────────────────────────────────────────

    def _finding(self, **kwargs) -> AgentFinding:
        """Shortcut to create a properly-typed AgentFinding."""
        # Sanitize string fields so raw HTTP responses don't break JSON serialization
        import re as _re
        _ctrl = _re.compile(r'[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]')
        for key in ("evidence", "description", "payload", "title", "remediation"):
            if key in kwargs and isinstance(kwargs[key], str):
                kwargs[key] = _ctrl.sub('', kwargs[key])
        return AgentFinding(
            finding_id=f"SI-{uuid.uuid4().hex[:10].upper()}",
            agent_id=self.agent_id,
            agent_type=self.agent_type,
            **kwargs,
        )

    async def _tool(self, name: str, **kwargs) -> Dict:
        """Run a tool via ToolRegistry in an executor (non-blocking)."""
        if not self.tool_registry:
            return {}
        loop = asyncio.get_event_loop()
        try:
            result = await loop.run_in_executor(
                None, lambda: self.tool_registry.run(name, **kwargs)
            )
            if hasattr(result, "to_dict"):
                return result.to_dict()
            return result if isinstance(result, dict) else {}
        except Exception as exc:
            logger.debug("[%s] Tool %s error: %s", self.name, name, exc)
            return {}

    def _boost_confidence(self, base: float, tech_stack: List[str],
                          target_techs: List[str]) -> float:
        tech_str = " ".join(t.lower() for t in tech_stack)
        if any(t.lower() in tech_str for t in target_techs):
            return min(base + 0.20, 0.95)
        return base


