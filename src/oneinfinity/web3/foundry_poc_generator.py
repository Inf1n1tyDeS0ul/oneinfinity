def generate(
    vuln_type: str,
    contract_name: str,
    finding_title: str,
    contract_address: str = "",
) -> FoundryPoC:
    """Generate a Foundry PoC for the given vulnerability type."""
    key = vuln_type.lower().replace("-", "_").replace(" ", "_")
    tmpl = _TEMPLATES.get(key, _TEMPLATES["default"])

    # Replace contract name in setup if needed
    setup = tmpl["setup"]
    if "{contract_name}" in setup:
        setup = setup.replace("{contract_name}", contract_name)
    if contract_address:
        setup = f"target = {contract_name}({contract_address});\n        {setup}"

    return FoundryPoC(
        finding_title=finding_title,
        contract_name=contract_name,
        vuln_type=vuln_type,
        test_code=tmpl["test"],
        setup_code=setup,
        description=tmpl.get("description", ""),
    )
