"""foundry_poc_generator.py — Foundry test PoC template generator for smart contract vulns."""
from __future__ import annotations

from dataclasses import dataclass
from typing import Optional


@dataclass
class FoundryPoC:
    finding_title: str
    contract_name: str
    vuln_type: str
    test_code: str
    setup_code: str = ""
    description: str = ""

    def full_test_file(self) -> str:
        return f"""// SPDX-License-Identifier: MIT
pragma solidity ^0.8.20;

import "forge-std/Test.sol";
import "forge-std/console.sol";

// PoC for: {self.finding_title}
// Vuln type: {self.vuln_type}
// Generated by OneInfinity

contract {self.contract_name}Exploit is Test {{
    {self.contract_name} target;

    function setUp() public {{
        {self.setup_code or f'target = new {self.contract_name}();'}
    }}

    function test_exploit() public {{
        {self.test_code}
    }}
}}
"""


